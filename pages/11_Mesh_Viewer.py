# ── Mesh loading / generation ──────────────────────────────────────────────────

def _auto_alpha(pts: np.ndarray) -> float:
    from scipy.spatial import KDTree
    sample = pts[: min(3000, len(pts))]
    d, _   = KDTree(sample).query(sample, k=2)
    return float(np.median(d[:, 1])) * 6.0


def _build_mesh_pyvista(coords: np.ndarray):
    """Point cloud -> (vertices, triangles) via Delaunay 3D."""
    import pyvista as pv
    alpha = _auto_alpha(coords)
    surf  = (
        pv.PolyData(coords.astype(np.float32))
        .delaunay_3d(alpha=alpha)
        .extract_surface(algorithm="dataset_surface")
        .triangulate()
    )
    tris = surf.faces.reshape(-1, 4)[:, 1:]
    return surf.points, tris


@st.cache_data(show_spinner=False)
def get_raw_data(snap: int, stride: int):
    """Return (coords, pressure) — always succeeds, always cached."""
    coords   = load_snapshot_coords(snap, stride)
    pressure = load_pressure_snapshot(snap, stride)
    return coords, pressure


@st.cache_data(show_spinner=False)
def get_mesh_data(snap: int, stride: int):
    """Return (verts, tris, pressure_on_mesh). Raises on failure so result is NOT cached."""
    # Load data directly (avoid calling a cached fn from within a cached fn)
    coords   = load_snapshot_coords(snap, stride)
    pressure = load_pressure_snapshot(snap, stride)

    # 1. Try pre-computed STL
    stl_path = MESH_DIR / f"snapshot_{snap:03d}.stl"
    verts, tris = None, None

    if stl_path.exists():
        try:
            import trimesh
            m     = trimesh.load(str(stl_path))
            verts = np.array(m.vertices, dtype=np.float64)
            tris  = np.array(m.faces)
        except Exception:
            pass

    # 2. Generate on-the-fly — raises if pyvista unavailable (not cached on failure)
    if verts is None:
        verts, tris = _build_mesh_pyvista(coords)

    # 3. Map pressure to mesh vertices via nearest-neighbour
    from scipy.spatial import KDTree
    _, idx           = KDTree(coords).query(verts, k=1)
    pressure_on_mesh = pressure[idx]

    return verts, tris, pressure_on_mesh


