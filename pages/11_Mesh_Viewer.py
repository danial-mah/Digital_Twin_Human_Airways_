"""
pages/7_Mesh_Viewer.py
======================
Solid surface mesh viewer for the Human Airways digital twin.

Point cloud vs mesh
-------------------
Every other page in this app renders the airway as ~42,000 floating dots
(a point cloud).  Here the same data is shown as a continuous triangulated
surface — the kind of 3D object that CFD tools, surgical planning software,
and HELYX actually work with.

The mesh is generated by Delaunay 3D triangulation of the point cloud, then
boundary surface extraction (alpha-shape style).  Pre-computed STLs from
scripts/export_mesh.py are loaded directly; otherwise the mesh is built
on-the-fly and cached for the session.
"""

